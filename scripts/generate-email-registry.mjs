#!/usr/bin/env node
/**
 * Generates src/lib/emailRegistry.generated.ts from the edge-function email
 * template registry, so the admin Email Status catalog can never drift from
 * the templates that actually exist.
 *
 * Run: node scripts/generate-email-registry.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const registryPath = resolve(
  root,
  "supabase/functions/_shared/transactional-email-templates/registry.ts"
);
const authDir = resolve(root, "supabase/functions/_shared/email-templates");

const src = readFileSync(registryPath, "utf8");
const block = src.slice(src.indexOf("export const TEMPLATES"));
const names = [...block.matchAll(/^\s*'([a-z0-9-]+)':/gm)].map((m) => m[1]);
if (names.length === 0) throw new Error("No templates parsed from registry.ts");

// Auth emails log under the Supabase action_type, not the template file name.
const authKeys = ["signup", "recovery", "magiclink", "email_change", "invite", "reauthentication"];

const out = `// AUTO-GENERATED by scripts/generate-email-registry.mjs — do not edit by hand.
// Source: supabase/functions/_shared/transactional-email-templates/registry.ts
// Regenerate after adding or removing an email template.

export const TRANSACTIONAL_TEMPLATE_NAMES = [
${names.map((n) => `  "${n}",`).join("\n")}
] as const;

export const AUTH_TEMPLATE_KEYS = [
${authKeys.map((n) => `  "${n}",`).join("\n")}
] as const;
`;

writeFileSync(resolve(root, "src/lib/emailRegistry.generated.ts"), out);
console.log(`Wrote ${names.length} transactional templates (auth dir: ${authDir}).`);
